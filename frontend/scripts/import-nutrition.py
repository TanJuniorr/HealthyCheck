"""Build the reviewed catalogue from the official USDA SR Legacy CSV archive.

Usage: python scripts/import-nutrition.py path/to/usda.zip path/to/migration.sql
Source: https://fdc.nal.usda.gov/download-datasets/ (SR Legacy, April 2018).
No missing nutrient is inferred. Portion weights are edible USDA portions.
"""
import csv
import hashlib
import io
import json
from pathlib import Path
import sys
import zipfile

root = Path(__file__).resolve().parents[2]
archive = Path(sys.argv[1])
migration = Path(sys.argv[2])
manifest = json.loads(Path(__file__).with_name('nutrition-foods.json').read_text(encoding='utf-8-sig'))
assert len({f['fdc_id'] for f in manifest}) == len(manifest) >= 100
z = zipfile.ZipFile(archive)
def rows(name):
    entry = next(n for n in z.namelist() if n.endswith('/' + name))
    return csv.DictReader(io.TextIOWrapper(z.open(entry), encoding='utf-8-sig'))
foods = {r['fdc_id']: r for r in rows('food.csv')}
ids = {f['fdc_id'] for f in manifest}
nutrients = {i: {} for i in ids}
for row in rows('food_nutrient.csv'):
    if row['fdc_id'] in ids and row['nutrient_id'] in ['1008', '1003', '1005', '1004']:
        nutrients[row['fdc_id']][row['nutrient_id']] = float(row['amount'])
# Explicitly reviewed single-fruit/egg portions (not cups or unverified averages).
portion_ids = {'173944': '93515', '171688': '89193', '169097': '84230',
               '169105': '84249', '171287': '88374', '173424': '92500', '172189': '90055'}
portions = {r['fdc_id']: r for r in rows('food_portion.csv') if r['id'] in portion_ids.values()}
seed = []
for food in manifest:
    fid = food['fdc_id']
    assert foods[fid]['description'] == food['name_en'], fid
    values = nutrients[fid]
    assert set(values) == {'1008', '1003', '1005', '1004'}, (fid, values)
    assert all(v >= 0 for v in values.values())
    metadata = dict(name_vi=food['name_vi'], name_en=food['name_en'], group=food['group'],
                    source='USDA SR Legacy 2018', source_id='usda-sr:' + fid,
                    source_url='https://fdc.nal.usda.gov/food-details/' + fid + '/nutrients', base_unit='g')
    for field in ['aliases', 'edible_portion']:
        if field in food:
            metadata[field] = food[field]
    if food['group'] == 'prepared':
        metadata['recipe_reference'] = True
    if fid in portion_ids:
        p = portions[fid]
        metadata.update(unit_weight_g=float(p['gram_weight']) / float(p['amount']),
                        unit_description=p['modifier'], portion_source_id=p['id'])
    seed.append(dict(name=food['name_vi'], category=food['group'], serving_size='100 g',
                     calories_per_100g=values['1008'], protein_per_100g=values['1003'],
                     carbs_per_100g=values['1005'], fat_per_100g=values['1004'], catalog_metadata=metadata))
seed_path = root / 'supabase/seeds/nutrition_usda.json'
seed_path.parent.mkdir(parents=True, exist_ok=True)
seed_path.write_text(json.dumps(dict(source_url='https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip',
                                    archive_sha256=hashlib.sha256(archive.read_bytes()).hexdigest(), foods=seed), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
payload = json.dumps(seed, ensure_ascii=False, separators=(',', ':'))
migration.write_text("""-- Official USDA SR Legacy 2018; generated by frontend/scripts/import-nutrition.py.
-- Preserve existing IDs, values, meal records, privileges and RLS policies.
ALTER TABLE public.foods ADD COLUMN IF NOT EXISTS catalog_metadata jsonb;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.foods'::regclass AND conname='foods_catalog_metadata_valid') THEN
  ALTER TABLE public.foods ADD CONSTRAINT foods_catalog_metadata_valid CHECK (
   catalog_metadata IS NULL OR (jsonb_typeof(catalog_metadata)='object'
    AND catalog_metadata->>'base_unit' = 'g'
    AND (NOT catalog_metadata ? 'unit_weight_g' OR
     (jsonb_typeof(catalog_metadata->'unit_weight_g')='number' AND (catalog_metadata->>'unit_weight_g')::numeric > 0))));
 END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS foods_catalog_source_id_unique
 ON public.foods ((catalog_metadata->>'source_id')) WHERE catalog_metadata->>'source_id' IS NOT NULL;
INSERT INTO public.foods (name,category,serving_size,calories_per_100g,protein_per_100g,carbs_per_100g,fat_per_100g,catalog_metadata)
SELECT s.name,s.category,s.serving_size,s.calories_per_100g,s.protein_per_100g,s.carbs_per_100g,s.fat_per_100g,s.catalog_metadata
FROM jsonb_to_recordset($usda$""" + payload + """$usda$::jsonb) AS s(name text,category text,serving_size text,calories_per_100g numeric,protein_per_100g numeric,carbs_per_100g numeric,fat_per_100g numeric,catalog_metadata jsonb)
WHERE NOT EXISTS (SELECT 1 FROM public.foods f WHERE f.catalog_metadata->>'source_id'=s.catalog_metadata->>'source_id')
ON CONFLICT DO NOTHING;
""", encoding='utf-8')
print(f'Generated {len(seed)} foods, {len(portions)} verified count portions.')
